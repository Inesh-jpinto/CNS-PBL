#!/usr/bin/env python3
"""
scripts/export_layers.py — ModelGuard Layer Export Script

Exports each layer (weight tensor) of a PyTorch model checkpoint to a
separate binary file in the output directory. The Java crypto service can
then hash these files directly without needing a Python dependency.

Usage:
    python scripts/export_layers.py [model_path] [output_dir]

    model_path : path to a .pt or .pth PyTorch checkpoint
                 (default: publisher/original_model.pth)
    output_dir : directory where layer_NNN.bin files will be written
                 (default: layers/)

Example:
    python scripts/export_layers.py resnet50.pt layers/

Output:
    layers/layer_000.bin   — first weight tensor (flattened raw bytes)
    layers/layer_001.bin   — second weight tensor
    ...
    layers/manifest.txt    — metadata listing: index, name, shape, dtype, size

Notes:
  - Only tensors that require grad (model weights) or are stored as float
    tensors are exported. Buffers such as running_mean / running_var are
    also included because tampering with them changes model behaviour.
  - Tensors are written as little-endian raw bytes via .numpy().tobytes().
  - This script intentionally avoids JSON output — the Java publisher reads
    the binary files directly (or you can call extract_to_json separately).
"""

import os
import sys
import struct
import argparse
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(
        description="Export PyTorch model layers to per-layer binary files for ModelGuard."
    )
    parser.add_argument(
        "model_path",
        nargs="?",
        default=os.path.join(
            Path(__file__).parent.parent, "publisher", "original_model.pth"
        ),
        help="Path to PyTorch .pt/.pth checkpoint (default: publisher/original_model.pth)",
    )
    parser.add_argument(
        "output_dir",
        nargs="?",
        default=os.path.join(Path(__file__).parent.parent, "layers"),
        help="Directory to write layer_NNN.bin files (default: layers/)",
    )
    parser.add_argument(
        "--include-buffers",
        action="store_true",
        default=True,
        help="Include non-parameter buffers (running stats etc.) — default: True",
    )
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Print per-layer details",
    )
    return parser.parse_args()


def export_layers(model_path: str, output_dir: str, include_buffers: bool = True, verbose: bool = False):
    """
    Load model_path and write each layer to a binary file.

    Returns:
        list of dicts: [{index, name, shape, dtype, size_bytes, output_path}]
    """
    try:
        import torch
    except ImportError:
        print(
            "ERROR: PyTorch is not installed.\n"
            "Install it with:  pip install torch --index-url https://download.pytorch.org/whl/cpu",
            file=sys.stderr,
        )
        sys.exit(1)

    model_path = Path(model_path).resolve()
    output_dir = Path(output_dir).resolve()

    if not model_path.exists():
        print(f"ERROR: Model file not found: {model_path}", file=sys.stderr)
        sys.exit(1)

    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"[ExportLayers] Loading: {model_path}")

    # Load state dict; weights_only=True is safer (no arbitrary code execution)
    try:
        state_dict = torch.load(str(model_path), map_location="cpu", weights_only=True)
    except TypeError:
        # Older PyTorch versions don't support weights_only
        state_dict = torch.load(str(model_path), map_location="cpu")

    # Flatten: if it's a full checkpoint (has 'state_dict' or 'model_state_dict'), unwrap
    if isinstance(state_dict, dict):
        for key in ("state_dict", "model_state_dict", "model"):
            if key in state_dict and isinstance(state_dict[key], dict):
                print(f"[ExportLayers] Detected full checkpoint — unwrapping '{key}'")
                state_dict = state_dict[key]
                break

    manifest_lines = [
        "# ModelGuard Layer Export Manifest",
        f"# Source: {model_path}",
        f"# Exported to: {output_dir}",
        f"# Generated by: scripts/export_layers.py",
        "#",
        "# index | name | shape | dtype | size_bytes | filename",
    ]

    layers_info = []
    total_bytes = 0

    for i, (name, tensor) in enumerate(state_dict.items()):
        # Convert to CPU numpy
        try:
            arr = tensor.cpu().float().detach().numpy()
        except Exception:
            # Some tensors (e.g. strings, object tensors) can't be converted; skip
            if verbose:
                print(f"  [skip] {name} — not a numeric tensor")
            continue

        raw_bytes = arr.tobytes()
        out_filename = f"layer_{i:03d}.bin"
        out_path = output_dir / out_filename

        with open(out_path, "wb") as f:
            f.write(raw_bytes)

        size = len(raw_bytes)
        total_bytes += size

        info = {
            "index": i,
            "name": name,
            "shape": list(arr.shape),
            "dtype": str(arr.dtype),
            "size_bytes": size,
            "output_path": str(out_path),
        }
        layers_info.append(info)

        manifest_line = f"{i:03d} | {name} | {list(arr.shape)} | {arr.dtype} | {size} | {out_filename}"
        manifest_lines.append(manifest_line)

        if verbose:
            print(f"  [{i:03d}] {name:50s} {str(list(arr.shape)):20s} {size:>10,} bytes → {out_filename}")
        else:
            print(f"  [{i:03d}] {name} → {out_filename} ({size:,} bytes)")

    # Write text manifest
    manifest_path = output_dir / "manifest.txt"
    with open(manifest_path, "w") as f:
        f.write("\n".join(manifest_lines) + "\n")

    print(f"\n[ExportLayers] Done!")
    print(f"  Layers exported : {len(layers_info)}")
    print(f"  Total bytes     : {total_bytes:,} ({total_bytes / 1024 / 1024:.2f} MB)")
    print(f"  Output directory: {output_dir}")
    print(f"  Manifest        : {manifest_path}")
    print(
        "\nNext step:\n"
        "  Run the Java publisher to hash each layer and build the Merkle tree:\n"
        "  java -cp \"crypto-java/out;crypto-java/lib/*\" modelguard.Main publish \\\n"
        "       <layerHashesJson> publisher/keys/private_key.pem \"Your Name\" manifest.json\n"
        "\n  Or use the web interface at http://localhost:5173/models/upload"
    )

    return layers_info


def generate_synthetic_layers(output_dir: str, n: int = 6, seed: int = 42):
    """
    Create N synthetic binary layer files without requiring PyTorch.
    Useful for testing the Java crypto pipeline without a real model.

    Each file is filled with deterministic pseudo-random bytes (no NumPy dependency).
    """
    import random

    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    sizes = [4096, 8192, 16384, 4096, 32768, 2048, 8192, 1024]  # bytes per layer

    print(f"[SyntheticLayers] Generating {n} synthetic layer files in {output_dir}")
    rng = random.Random(seed)
    for i in range(n):
        size = sizes[i % len(sizes)]
        data = bytes([rng.randint(0, 255) for _ in range(size)])
        out = output_dir / f"layer_{i:03d}.bin"
        out.write_bytes(data)
        print(f"  [synthetic] layer_{i:03d}.bin  {size:,} bytes")

    print(f"\n[SyntheticLayers] {n} synthetic layers written to {output_dir}")


if __name__ == "__main__":
    args = parse_args()

    # If the user explicitly passed a path ending in "synthetic", generate test data
    if str(args.model_path).lower().endswith("synthetic"):
        n = 6
        generate_synthetic_layers(args.output_dir, n=n)
    else:
        export_layers(
            model_path=args.model_path,
            output_dir=args.output_dir,
            include_buffers=args.include_buffers,
            verbose=args.verbose,
        )
