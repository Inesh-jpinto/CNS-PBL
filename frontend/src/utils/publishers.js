// Flat array of all publishers for quick lookup
export const ALL_PUBLISHERS = PUBLISHER_CATEGORIES.flatMap(cat => cat.publishers);

// Get a random trusted publisher
export function getRandomPublisher() {
  const idx = Math.floor(Math.random() * ALL_PUBLISHERS.length);
  return ALL_PUBLISHERS[idx];
}

// Look up publisher by id/name
export function findPublisher(nameOrId) {
  return ALL_PUBLISHERS.find(
    p => p.id === nameOrId || p.name === nameOrId || p.displayName === nameOrId
  );
}
